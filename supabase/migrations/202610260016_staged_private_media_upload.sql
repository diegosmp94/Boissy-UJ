-- Boissy UJ | 2026-10-26 | step 79 | staged private media upload.
-- Only an AAL2 admin may PUT a new file into a pre-registered, unpublished
-- article asset. No public upload, no overwrite, no object LIST or DELETE.
-- The metadata creation RPC from step 78 remains the only INSERT to the
-- 12-assets-per-article registry; this migration creates no content.
begin;

-- The metadata RLS currently exposes approved media to visitors only.
-- AAL2 admins need a separate read-only policy so the Storage INSERT
-- authorization can correlate an upload with its pre-registered draft row.
-- The table's column-level SELECT grant stays unchanged. No direct UPDATE,
-- INSERT or DELETE is granted for news_media_assets.
drop policy if exists news_media_admin_staged_read on public.news_media_assets;
create policy news_media_admin_staged_read
 on public.news_media_assets
 for select to authenticated
 using (coalesce((select app_private.is_admin()),false));

-- A unique, unguessable path is generated by the client, registered as a
-- nonvisible, unreviewed article asset, and then uploaded without upsert.
-- No direct upload to an approved/visible path, nor to an unregistered name.
drop policy if exists boissy_admin_staged_media_upload on storage.objects;
create policy boissy_admin_staged_media_upload
 on storage.objects
 for insert to authenticated
 with check (
  bucket_id='boissy-uj-approved'
  and coalesce((select app_private.is_admin()),false)
  and name ~ '^incoming/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}[.](jpg|jpeg|png|webp|avif|mp4|webm)$'
  and char_length(name)<=180
  and exists(
   select 1 from public.news_media_assets a
   join public.news_posts p on p.id=a.post_id
   where a.storage_path=name
     and a.visible=false and a.rights_reviewed=false
     and p.visibility='public'
  )
 );

-- INSERT only; the existing SELECT policy remains restricted to signed
-- read operations for already approved/published files.
-- No UPDATE, DELETE, SELECT-list or bucket-public grants are introduced.
comment on policy boissy_admin_staged_media_upload on storage.objects is
 'AAL2 admin, create-only in private incoming/, after draft asset registration; no upsert or automatic publication.';
commit;
